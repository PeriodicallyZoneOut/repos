package com.example.myapplication;

public class Student {
    public String id;
    public String name;
    public String className;
    public double gpa;
    public int imageRes;

    public Student(String id, String name, String className, double gpa, int imageRes) {
        this.id = id;
        this.name = name;
        this.className = className;
        this.gpa = gpa;
        this.imageRes = imageRes;
    }
}
